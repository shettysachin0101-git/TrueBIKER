// Helper to generate a clean list of base bikes without variants to avoid duplication
const generateAllBikes = () => {
  const allBikesList = [];

  for (let base of baseBikes) {
    const cleanName = `${base.brand}-${base.model}`
      .toLowerCase()
      .replace(/\s+/g, '-')
      .replace(/[^a-z0-9\-]/g, '')
      .replace(/-+/g, '-');

    allBikesList.push({
      bikeName: `${base.brand} ${base.model}`,
      brand: base.brand,
      engineCC: Math.round(base.engineCC),
      mileage: base.mileage,
      topSpeed: base.topSpeed,
      price: base.price,
      fuelType: base.fuelType,
      transmission: base.transmission,
      weight: Math.round(base.weight),
      seatHeight: base.seatHeight,
      reliabilityScore: base.reliabilityScore,
      beginnerFriendly: base.beginnerFriendly,
      resaleValue: base.resaleValue,
      categories: base.categories,
      features: Array.from(new Set(base.features)),
      pros: Array.from(new Set(base.pros)),
      cons: Array.from(new Set(base.cons)),
      imageUrl: `/images/${cleanName}.jpg`,
      officialWebsite: base.officialWebsite,
      launchYear: base.launchYear,
      availability: 'Available'
    });
  }

  return allBikesList;
};

const seedDatabase = async () => {
  try {
    if (require.main === module || mongoose.connection.readyState === 0) {
      // Start in-memory server if port 27017 is free
      await mongoMemoryServer.start();

      console.log('Connecting to database...');
      await mongoose.connect(MONGODB_URI);
      console.log('Successfully connected to MongoDB.');
    }

    // 1. Clear database collections
    console.log('Purging existing data...');
    await Bike.deleteMany({});
    await User.deleteMany({});

    // 2. Generate and Insert Bikes
    const bikesToInsert = generateAllBikes();
    console.log(`Generated ${bikesToInsert.length} unique motorcycle records.`);

    // Use duplicate check by name before inserting
    const uniqueBikes = [];
    const nameSet = new Set();

    for (let bike of bikesToInsert) {
      if (!nameSet.has(bike.bikeName)) {
        nameSet.add(bike.bikeName);
        uniqueBikes.push(bike);
      }
    }

    console.log(`Seeding ${uniqueBikes.length} unique bikes into MongoDB...`);
    const insertedBikes = await Bike.insertMany(uniqueBikes);
    console.log(`Successfully seeded ${insertedBikes.length} motorcycles.`);

    // 3. Write data to bikeSeed.json for reference/backup
    const seedFilePath = path.join(__dirname, 'bikeSeed.json');
    fs.writeFileSync(seedFilePath, JSON.stringify(uniqueBikes, null, 2));
    console.log(`Wrote seed data backup to ${seedFilePath}`);

    // 4. Seed default administrator
    const adminEmail = 'sachinshetty@gmail.com';
    const adminPassword = '12345';

    const salt = await bcrypt.genSalt(10);
    const hashedPassword = await bcrypt.hash(adminPassword, salt);

    const adminUser = new User({
      name: 'System Admin',
      email: adminEmail,
      password: hashedPassword,
      role: 'admin',
      preferences: {
        ridingTypes: ['Street', 'Cruiser'],
        budgetMin: 100000,
        budgetMax: 500000,
        brands: ['Honda', 'Yamaha'],
        features: ['ABS', 'Mileage'],
        beginnerFriendly: true,
        resaleValue: 'High',
        comfortImportance: true,
        mileageImportance: true,
        reliabilityImportance: true
      }
    });

    await adminUser.save();
    console.log(`✅ Default Admin Seeded!`);
    console.log(`   - Email: ${adminEmail}`);
    console.log(`   - Password: ${adminPassword}`);

    if (require.main === module) {
      mongoose.disconnect();
      console.log('Database seeding process complete. Disconnected.');
      process.exit(0);
    }
  } catch (err) {
    console.error('❌ Seeding error:', err);
    if (require.main === module) {
      process.exit(1);
    } else {
      throw err;
    }
  }
};

if (require.main === module) {
  seedDatabase();
}

